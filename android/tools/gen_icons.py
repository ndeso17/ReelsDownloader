def wrap(path: str, width: int = 88) -> list[str]:
    """Pecah path jadi potongan yang disambung operator `+`."""
    parts, line = [], ""
    for token in path.split(" "):
        candidate = token if not line else line + " " + token
        if len(candidate) > width and line:
            parts.append(line)
            line = token
        else:
            line = candidate
    if line:
        parts.append(line)
    return parts


